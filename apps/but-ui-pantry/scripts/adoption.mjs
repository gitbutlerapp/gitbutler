// What but.dev uses of but-ui-react, for the pantry's Adoption page: every name it imports from
// each of the library's files, in how many of its files and how many times, read off a but-dev
// checkout at a commit, into src/adoption.json.
//
//   node scripts/adoption.mjs <but-dev checkout> [ref, origin/main]
//
// It reads the commit, not the working tree, so a dev-only branch checked out there doesn't
// count. Fetch there first for the latest.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const out = resolve(here, "../src/adoption.json");

if (process.argv.length < 3) {
	process.stderr.write("Usage: node scripts/adoption.mjs <but-dev checkout> [ref]\n");
	process.exit(1);
}
const [checkout = "", ref = "origin/main"] = process.argv.slice(2);

/** @type {(cwd: string, ...args: Array<string>) => string} */
const git = (cwd, ...args) => execFileSync("git", args, { cwd, encoding: "utf8" }).trim();
/** @type {(...args: Array<string>) => string} */
const butDev = (...args) => git(checkout, ...args);

const commit = butDev("rev-parse", ref);
const date = butDev("show", "-s", "--format=%cI", commit);

// The commit of this repository but.dev's package.json pins the library at.
const pin = /gitbutler#([0-9a-f]{7,40})&path:packages\/but-ui-react/.exec(
	butDev("show", `${commit}:web/package.json`),
)?.[1];
// How many of the library's commits on master it doesn't have yet, when this clone knows the pin.
let behind = null;
if (pin !== undefined) {
	try {
		behind = Number(
			git(root, "rev-list", "--count", `${pin}..origin/master`, "--", "packages/but-ui-react"),
		);
	} catch {
		process.stderr.write(`This clone doesn't have ${pin}; fetch to count how far behind it is.\n`);
	}
}

const IMPORT =
	/import\s+(?:type\s+)?\{([^}]*)\}\s*from\s*["']@gitbutler\/but-ui-react\/([^"']+)["']/g;

/** @type {Record<string, { files: number, names: Record<string, { files: number, uses: number }> }>} */
const modules = {};
const files = butDev("grep", "-l", "@gitbutler/but-ui-react/", commit, "--", "*.ts", "*.tsx")
	.split("\n")
	.filter((line) => line !== "");
for (const line of files) {
	const path = line.slice(commit.length + 1);
	const source = butDev("show", `${commit}:${path}`);
	const body = source.replace(IMPORT, "");
	for (const [, list = "", module = ""] of source.matchAll(IMPORT)) {
		const entry = (modules[module] ??= { files: 0, names: {} });
		entry.files += 1;
		for (const item of list.split(",")) {
			// `type IconName`, `Dropdown as Menu`: the library's name, counted by the local one.
			const [name, local = name] = item
				.trim()
				.replace(/^type\s+/, "")
				.split(/\s+as\s+/);
			if (name === "") continue;
			const uses = body.match(new RegExp(String.raw`\b${local}\b`, "g"))?.length ?? 0;
			const named = (entry.names[name] ??= { files: 0, uses: 0 });
			named.files += 1;
			named.uses += uses;
		}
	}
}

const sorted = Object.fromEntries(
	Object.entries(modules)
		.sort(([a], [b]) => a.localeCompare(b))
		.map(([module, entry]) => [
			module,
			{
				files: entry.files,
				names: Object.fromEntries(
					Object.entries(entry.names).sort(([a], [b]) => a.localeCompare(b)),
				),
			},
		]),
);

writeFileSync(
	out,
	`${JSON.stringify(
		{
			$description:
				"Generated by scripts/adoption.mjs from a but-dev checkout; rerun it, don't edit this.",
			commit,
			date,
			pin: pin ?? null,
			behind,
			files: files.length,
			modules: sorted,
		},
		null,
		"\t",
	)}\n`,
);
process.stdout.write(
	`but.dev ${commit.slice(0, 7)} (${date}): ${Object.keys(sorted).length} modules in ${files.length} files, pinned at ${pin ?? "?"}${behind === null ? "" : `, ${behind} library commits behind master`}.\n`,
);
