import { liftComposedColors } from "./composed-colors.mjs";
import { accentCss, accentSetting } from "./generate-accents.mjs";
import { densityCss, densitySetting } from "./generate-density.mjs";
import { radiusCss, radiusSetting } from "./generate-radius.mjs";
import { generateShadowVars } from "./generate-shadow-vars.mjs";
import { stripCollectionPrefix } from "./terrazzo-css-helpers.mjs";
import { tokensData } from "./tokens-data.mjs";
import { spawn } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const TOKENS_CSS_PATH = resolve("tokens/tokens.css");
const SETTINGS_PATH = resolve("tokens/settings.json");
const TOKENS_DATA_PATH = resolve("tokens/tokens.json");
const TOKEN_JSON_PATHS = [
	resolve("tokens/json/core.tokens.json"),
	resolve("tokens/json/semantic.tokens.json"),
	resolve("tokens/json/ramps.tokens.json"),
];

const SETTINGS_DESCRIPTION =
	"Generated by the build from tokens.css and the rules in scripts/generate-accents, -radius and -density.mjs; edit those, not this file. Every setting a person can pick, as data: `values` has each choice, Figma's (`default`) included, as the tokens it sets. Token names are tokens.css's without --but-, lengths are px, and an accent's values name the ramp step each token points at.";

const TOKENS_DATA_DESCRIPTION =
	"Generated by the build from tokens.css; change the tokens in Figma, not this file. The tokens as data, for a platform that can't read CSS: `colors` has what each colour token comes to in light and in dark, as sRGB hex with its alpha last when it has one, and `lengths` has each length in px. Names are tokens.css's without --but-. These are Figma's values; what a setting changes is in settings.json.";

const isWatchMode = process.argv.includes("--watch");

const composedColors = liftComposedColors(TOKEN_JSON_PATHS, resolve(".terrazzo"));

// Figma variable descriptions, keyed by CSS custom property name. They are
// written above each declaration so tokens.css says when to use a token, for
// people and for agents reading it from node_modules.
function readDescriptions() {
	const descriptions = new Map();
	function walk(node, path) {
		if (!node || typeof node !== "object") return;
		if ("$type" in node) {
			const name = stripCollectionPrefix(path.join("."));
			const description = node.$description?.trim();
			if (name && description) descriptions.set(name, description);
			return;
		}
		for (const [key, child] of Object.entries(node)) {
			if (!key.startsWith("$")) walk(child, [...path, key]);
		}
	}
	for (const file of TOKEN_JSON_PATHS) {
		walk(JSON.parse(readFileSync(file, "utf8")), []);
	}
	return descriptions;
}

function getBlock(css, selector) {
	const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
	const match = css.match(new RegExp(`${escaped}\\s*\\{([\\s\\S]*?)\\}`, "m"));
	return match?.[1] ?? "";
}

function parseDeclarations(block) {
	const declarations = [];
	const index = new Map();

	for (const line of block.split("\n")) {
		const match = line.match(/^\s*(--[^:]+):\s*(.+?);\s*(?:\/\*.*\*\/)?\s*$/);
		if (!match) continue;

		const [, name, value] = match;
		index.set(name, declarations.length);
		declarations.push({ name, value });
	}

	return {
		declarations,
		index,
	};
}

function stringifyDeclarations(declarations, descriptions) {
	return declarations
		.map(({ name, value }) => {
			const description = descriptions.get(name);
			const line = `  ${name}: ${value};`;
			return description ? `  /* ${description.replaceAll("*/", "* /")} */\n${line}` : line;
		})
		.join("\n");
}

function buildLightDarkCss(sourceCss) {
	const lightBlock = getBlock(sourceCss, ":root");
	const darkBlock = getBlock(sourceCss, ":root.dark");

	if (!lightBlock || !darkBlock) {
		if (isWatchMode) {
			return sourceCss;
		}

		throw new Error("Expected both :root and :root.dark token blocks in tokens/tokens.css.");
	}

	const light = parseDeclarations(lightBlock);
	const dark = parseDeclarations(darkBlock);
	const merged = light.declarations.map(({ name, value }) => {
		const darkIndex = dark.index.get(name);
		if (darkIndex === undefined) {
			return { name, value };
		}

		const darkValue = dark.declarations[darkIndex].value;
		if (value === darkValue) {
			return { name, value };
		}

		return { name, value: `light-dark(${value}, ${darkValue})` };
	});

	for (const declaration of dark.declarations) {
		if (light.index.has(declaration.name)) continue;
		merged.push(declaration);
	}

	// This pass runs again over its own output, so it adds only what's missing.
	for (const declaration of composedColors) {
		if (!light.index.has(declaration.name)) merged.push(declaration);
	}

	return `/* -------------------------------------------\n *  Autogenerated by ⛋ Terrazzo. DO NOT EDIT!\n * ------------------------------------------- */\n\n:root {\n  color-scheme: light dark;\n${stringifyDeclarations(merged, readDescriptions())}\n}\n\n:root.light {\n  color-scheme: light;\n}\n\n:root.dark {\n  color-scheme: dark;\n}\n`;
}

function write(path, contents) {
	let current;
	try {
		current = readFileSync(path, "utf8");
	} catch {
		// Not written yet.
	}
	if (contents !== current) writeFileSync(path, contents, "utf8");
}

function postprocessTokens() {
	const tokensCss = generateShadowVars(buildLightDarkCss(readFileSync(TOKENS_CSS_PATH, "utf8")));
	// What a person can pick, worked out once as data. tokens/settings.json holds it for whatever
	// can't read CSS, and tokens.css takes its blocks from the same objects, so the two can't
	// differ.
	const accent = accentSetting(tokensCss);
	const radius = radiusSetting(tokensCss);
	const density = densitySetting(tokensCss);
	write(
		TOKENS_CSS_PATH,
		[tokensCss, accentCss(accent), radiusCss(radius), densityCss(density)].join("\n"),
	);
	write(
		SETTINGS_PATH,
		`${JSON.stringify({ $description: SETTINGS_DESCRIPTION, accent, radius, density }, null, "\t")}\n`,
	);
	// A colour to a line, so a changed token reads as one line in a diff.
	const data = JSON.stringify(
		{ $description: TOKENS_DATA_DESCRIPTION, ...tokensData(tokensCss) },
		null,
		"\t",
	).replace(/\{\n\t+"light": (".*?"),\n\t+"dark": (".*?")\n\t+\}/g, '{ "light": $1, "dark": $2 }');
	write(TOKENS_DATA_PATH, `${data}\n`);
}

const tzArgs = ["exec", "tz", "build"];
if (isWatchMode) {
	tzArgs.push("--watch");
}

const child = spawn("pnpm", tzArgs, {
	cwd: process.cwd(),
	stdio: ["inherit", "pipe", "pipe"],
});

child.stdout.setEncoding("utf8");
child.stdout.on("data", (chunk) => {
	process.stdout.write(chunk);
	if (chunk.includes("tokens built") || (!isWatchMode && chunk.includes("Build complete"))) {
		postprocessTokens();
	}
});

child.stderr.setEncoding("utf8");
child.stderr.on("data", (chunk) => {
	process.stderr.write(chunk);
});

child.on("close", (code) => {
	if (code === 0 && !isWatchMode) {
		postprocessTokens();
	}

	process.exit(code ?? 0);
});
